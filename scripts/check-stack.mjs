import { chromium } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
mkdirSync('artifacts', {recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const results=[];
try{
 for(const width of [320,375,430,768,1024,1440,1920]){
  const context=await browser.newContext({viewport:{width,height:1000},reducedMotion:'no-preference'});
  const page=await context.newPage();
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`)});
  await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
  assert.equal(await page.locator('#home').evaluate(el=>el.nextElementSibling.id),'stack');
  await page.getByRole('link',{name:'Scroll to explore'}).click();
  const carousel=page.getByRole('region',{name:'Featured technologies'});
  await carousel.waitFor();
  await page.waitForFunction(()=>Math.abs(window.scrollY-document.getElementById('stack').offsetTop+100)<50);
  await page.evaluate(async()=>{const image=new Image();image.src='/images/stack/tech-atlas.webp';await image.decode()});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Overflow at ${width}`);
  await carousel.getByRole('button',{name:'Next technology'}).click();
  await carousel.getByRole('status').filter({hasText:'React'}).waitFor();
  await carousel.getByRole('button',{name:'Previous technology'}).click();
  await carousel.getByRole('status').filter({hasText:'Java'}).waitFor();
  await carousel.focus();
  await page.keyboard.press('End');
  await carousel.getByRole('status').filter({hasText:'Docker'}).waitFor();
  await page.keyboard.press('Home');
  await page.waitForTimeout(850);
  await carousel.getByRole('button',{name:'Explore Java',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Java',exact:true});
  await dialog.waitFor();
  assert.equal(await page.evaluate(()=>document.body.style.overflow),'hidden');
  await page.keyboard.press('Escape');
  assert.equal(await dialog.count(),0);
  assert.equal(await carousel.getByRole('button',{name:'Explore Java',exact:true}).evaluate(el=>el===document.activeElement),true);
  const start=await carousel.locator('.tech-face-active .tech-art').boundingBox();
  await page.mouse.move(start.x+start.width/2,start.y+start.height/2);
  await page.mouse.down();
  await page.mouse.move(start.x+start.width/2+150,start.y+start.height/2,{steps:15});
  await page.mouse.up();
  await page.waitForTimeout(850);
  assert.ok(!(await carousel.getByRole('status').textContent()).includes('Java, technology'),'Drag should change card');
  assert.equal(await page.getByRole('dialog').count(),0,'Dragging must not open a card');
  await carousel.focus();await page.keyboard.press('Home');await page.waitForTimeout(850);
  const a11y=await new AxeBuilder({page}).include('#stack').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  assert.deepEqual(a11y.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.failureSummary)})),[],`Stack accessibility at ${width}`);
  if([375,1440].includes(width))await page.screenshot({path:`artifacts/stack-${width}.png`});
  assert.deepEqual(errors,[]);
  results.push({width,overflow:false,errors:0,accessibilityViolations:0,keyboard:true,drag:true,dialog:true});
  await context.close();
 }
 const context=await browser.newContext({viewport:{width:375,height:1000},reducedMotion:'reduce'});
 const page=await context.newPage();
 await page.goto('http://127.0.0.1:4173/#stack',{waitUntil:'networkidle'});
 const carousel=page.getByRole('region',{name:'Featured technologies'});await carousel.waitFor();
 assert.equal(await carousel.locator('.tech-cylinder').count(),0);
 assert.equal(await carousel.locator('.tech-face').count(),1);
 for(let i=0;i<8;i++)await carousel.getByRole('button',{name:'Next technology'}).click();
 assert.ok((await carousel.getByRole('status').textContent()).includes('Java'));
 await context.close();
 writeFileSync('artifacts/stack-results.json',JSON.stringify({results,reducedMotion:'flat card; full cycle verified'},null,2));
 console.log(JSON.stringify({results,reducedMotion:'passed'},null,2));
}finally{await browser.close()}
